#!/usr/bin/env node

/**
 * Helper script to ensure context directory structure exists at project root
 * Creates context/, context/workflows/, and context/business-rules/ directories
 * Also creates a README.md to explain the structure
 */

const fs = require('fs');
const path = require('path');

// Directories to create relative to project root
const contextDirs = [
  'context',
  'context/workflows',
  'context/business-rules'
];

// Get project root (current working directory where script is run)
const projectRoot = process.cwd();

console.log('Setting up context directory structure...\n');

// Create directories
contextDirs.forEach(dir => {
  const fullPath = path.join(projectRoot, dir);
  
  if (!fs.existsSync(fullPath)) {
    fs.mkdirSync(fullPath, { recursive: true });
    console.log(`✓ Created ${dir}/`);
  } else {
    console.log(`✓ ${dir}/ already exists`);
  }
});

// Create README.md in context/ directory
const readmePath = path.join(projectRoot, 'context', 'README.md');

if (!fs.existsSync(readmePath)) {
  const readmeContent = `# System Context Documentation

This directory contains business domain knowledge for the Caleo platform.

## Structure

- \`domain.md\` - Core domain concepts and terminology
- \`entities.md\` - Data models and relationships
- \`workflows/\` - Individual workflow documentation (one file per workflow)
- \`business-rules/\` - Business rule documentation (one file per rule category)

## Purpose

This context complements the technical documentation in AGENTS.md files by capturing:
- **What** the system does (business perspective)
- **Why** certain rules exist (business rationale)
- **How** users accomplish tasks (workflows)
- **Key terminology** and concepts (domain language)

## Organization

### Domain & Entities (Single Files)
- \`domain.md\` - Overarching domain concepts and terminology
- \`entities.md\` - Business entities and their relationships

### Workflows (Multiple Files)
Each workflow is documented in its own file:
- \`workflows/shift-creation.md\`
- \`workflows/shift-assignment.md\`
- \`workflows/shift-approval.md\`
- etc.

### Business Rules (Multiple Files)
Each business rule category is documented in its own file:
- \`business-rules/eligibility.md\`
- \`business-rules/scheduling-constraints.md\`
- \`business-rules/overtime-calculation.md\`
- etc.

## How to Use

Use the \`context-creator\` skill to add or update documentation in this directory.

The skill will guide you through an interactive Q&A process to capture business domain knowledge and automatically create/update the appropriate files.

## Relationship to AGENTS.md

**Context files (here)**: Business perspective - what/why  
**AGENTS.md files**: Technical perspective - how

Context documentation focuses on business rules, workflows, and domain concepts that help understand the "business logic" of the system. AGENTS.md files focus on code patterns, technical architecture, and implementation details.

Cross-reference between the two:
- Context files link to AGENTS.md for technical implementation
- AGENTS.md files link to context/ for business rationale

## Maintenance

- Start with brief summaries; expand over time
- Use TODO markers for future expansion
- Update as business rules evolve
- Keep synchronized with actual system behavior

---

Generated by context-creator skill
`;

  fs.writeFileSync(readmePath, readmeContent);
  console.log('✓ Created context/README.md');
} else {
  console.log('✓ context/README.md already exists');
}

console.log('\n✓ Context directory structure ready!');
console.log('\nNext steps:');
console.log('  1. Use the context-creator skill to start documenting');
console.log('  2. Begin with core domain concepts or a key workflow');
console.log('  3. Expand documentation incrementally over time\n');
